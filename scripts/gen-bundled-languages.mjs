// T4: turns the accepted language files (docs/languages/packs/<code>.json) into languages shipped inside the app.
// Writes public/languages/<code>.js (one script per language, loaded only when the user picks that language) and
// src/config/bundledlanguages.ts (the list the Settings row offers). Runs first in `npm run build`; a wrong pack stops the build.
import {readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, unlinkSync} from 'node:fs';
import {readEnglish} from './gen-language-base.mjs';

const root = new URL('../', import.meta.url);
const PACKS = new URL('docs/languages/packs/', root);
const OUT = new URL('public/languages/', root);
const INDEX = new URL('src/config/bundledlanguages.ts', root);
const ph = (s) => (String(s).match(/\{\w+\}/g) || []).sort().join(',');
const CONTROL = /[\u0000-\u0009\u000b-\u001f\u007f]/;
// Keys whose text may be empty (a language without a plural ending, e.g. Thai, writes ""). Same list in src/lib/langpack.ts and scripts/lang-check.mjs.
const EMPTY_OK = ['homekey.pluralSuffix'];

export function readBundled () {
  const en = readEnglish();
  const list = [], errors = [];
  const files = existsSync(PACKS) ? readdirSync(PACKS).filter((f) => f.endsWith('.json')).sort() : [];
  for (const f of files) {
    const bad = (m) => errors.push(`${f}: ${m}`);
    let p;
    try { p = JSON.parse(readFileSync(new URL(f, PACKS), 'utf8').replace(/^\uFEFF/, '')); } catch (e) { bad('not valid JSON'); continue; }
    const code = p && typeof p.code === 'string' ? p.code.trim() : '';
    const name = p && typeof p.language === 'string' ? p.language.trim() : '';
    if (p.format !== 1) bad('"format" must be 1');
    if (!/^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})?$/.test(code) || code.toLowerCase() === 'en') bad('"code" must be a language code such as de or pt-BR (not en)');
    else if (f !== code + '.json') bad(`the file must be named ${code}.json`);
    if (!name || name.length > 30 || CONTROL.test(name)) bad('"language" must be 1 to 30 characters');
    const strings = {};
    for (const k of Object.keys(p.strings || {})) {
      const v = p.strings[k];
      if (!(k in en)) continue;                                  // unknown keys are left out, as when a file is loaded
      if (typeof v !== 'string' || (!v && EMPTY_OK.indexOf(k) < 0) || v.length > 1000 || CONTROL.test(v) || ph(v) !== ph(en[k])) { bad(`bad text or placeholders: ${k}`); continue; }
      strings[k] = v;
    }
    if (!Object.keys(strings).length) bad('no text matches the English keys');
    if (!errors.some((e) => e.startsWith(f + ':'))) list.push({id: code, name, strings});
  }
  return {list, errors};
}

export const scriptText = (l) =>
  `window.__hearthLang&&window.__hearthLang(${JSON.stringify(l.id)},${JSON.stringify(l.strings).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')});\n`;
export const indexText = (list) =>
  `// Generated by scripts/gen-bundled-languages.mjs from docs/languages/packs/*.json. Do not edit.\n` +
  `export const BUNDLED_LANGUAGES: readonly {id: string; name: string}[] = [${list.map((l) => `\n\t{id: ${JSON.stringify(l.id)}, name: ${JSON.stringify(l.name)}}`).join(',')}${list.length ? '\n' : ''}];\n`;

if (process.argv[1] && process.argv[1].endsWith('gen-bundled-languages.mjs')) {
  const {list, errors} = readBundled();
  if (errors.length) { console.error('Language packs refused:\n  ' + errors.join('\n  ')); process.exit(1); }
  mkdirSync(OUT, {recursive: true});
  for (const f of readdirSync(OUT)) if (f.endsWith('.js')) unlinkSync(new URL(f, OUT));
  for (const l of list) writeFileSync(new URL(l.id + '.js', OUT), scriptText(l));
  writeFileSync(INDEX, indexText(list));
  console.log('bundled languages: ' + (list.map((l) => l.id).join(', ') || 'none'));
}
