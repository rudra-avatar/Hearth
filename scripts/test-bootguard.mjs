// Boot guard S3a (src/lib/bootguardcmd.ts): state, decisions, revert plan, marker text. S3c (src/lib/bootguardflow.ts): what the page does with the marker.   Run: npm test
import {build} from 'esbuild';
const out = new URL('../node_modules/.cache-bootguard-test.mjs', import.meta.url).pathname;
await build({entryPoints: [new URL('../src/lib/bootguardcmd.ts', import.meta.url).pathname], bundle: true, format: 'esm', outfile: out, platform: 'node', logLevel: 'error'});
const c = await import(out);
let fail = 0;
const eq = (a, b, m) => { const ok = JSON.stringify(a) === JSON.stringify(b); if (!ok) { fail++; console.log('FAIL', m, JSON.stringify(a), '!=', JSON.stringify(b)); } else console.log('ok  ', m); };
const E = c.EMPTY_GUARD;
eq(c.guardAllowed(true), true, 'allowed in the legacy bundle');
eq(c.guardAllowed(false), false, 'not allowed in the main bundle');
eq(c.guardActive(E), false, 'empty state is off');
const a = c.applyChange(E, 'inputAdded');
eq(c.guardActive(a) && a.input && !a.powerOn, true, 'input row turns the guard on');
const b = c.applyChange(a, 'powerOnSet');
eq([b.input, b.powerOn], [true, true], 'both rows can be on');
eq(c.guardActive(c.applyChange(b, 'inputRemoved')), true, 'still on while the power-on app is set');
eq(c.guardActive(c.applyChange(c.applyChange(b, 'inputRemoved'), 'powerOnCleared')), false, 'off when both are off');
eq(c.bootSeen(E).tries, 0, 'a boot without a row on is not counted');
eq(c.decide(a), 'none', 'no boot seen: nothing to do');
let s = c.bootSeen(a);
eq(c.decide(s), 'retry', 'first boot without Hearth: retry');
s = c.bootSeen(s);
eq(c.decide(s), 'retry', 'second boot without Hearth: retry (RETRY_BOOTS 2)');
s = c.bootSeen(s);
eq(c.decide(s), 'revert', 'third boot without Hearth: revert');
eq(c.decide(c.hearthReached(s)), 'none', 'Hearth reached: count restarts');
eq(c.hearthReached(a), a, 'reached with a clean count changes nothing');
eq(c.applyChange(c.bootSeen(a), 'inputAdded').tries, 0, 'a new change restarts the count');
eq(c.applyChange({...b, reverted: true}, 'inputAdded').reverted, false, 'a new change clears the reverted note');
eq(c.revertPlan(b), ['removeInput', 'clearPowerOn'], 'plan: input first, then power-on app');
eq(c.revertPlan(a), ['removeInput'], 'plan: input only');
eq(c.revertPlan(E), [], 'plan: nothing');
eq(c.afterRevert(b, false, false), {input: false, powerOn: false, tries: 0, reverted: true}, 'proved removed: all clear, reverted noted');
eq(c.afterRevert(b, true, false), {input: true, powerOn: false, tries: 0, reverted: true}, 'input still listed stays in the state');
eq(c.afterRevert(a, true, false), {input: true, powerOn: false, tries: 0, reverted: false}, 'nothing proved: not noted as reverted');
const round = {input: true, powerOn: false, tries: 2, reverted: false};
eq(c.parseGuard(c.serializeGuard(round)), round, 'marker round trip');
eq(c.parseGuard('garbage\ninput=2\ntries=x'), E, 'unreadable marker gives the empty state');
eq(c.parseGuard(''), E, 'empty marker gives the empty state');
eq(c.serializeGuard(round), 'input=1\npowerOn=0\ntries=2\nreverted=0\n', 'marker text is plain key=value lines');

// ----- S3c: bootguardflow.ts -----
const outFlow = new URL('../node_modules/.cache-bootguardflow-test.mjs', import.meta.url).pathname;
await build({entryPoints: [new URL('../src/lib/bootguardflow.ts', import.meta.url).pathname], bundle: true, format: 'esm', outfile: outFlow, platform: 'node', logLevel: 'error'});
const f = await import(outFlow);
const none = '';
const inOn = c.serializeGuard({input: true, powerOn: false, tries: 0, reverted: false});
const bothOn = c.serializeGuard({input: true, powerOn: true, tries: 0, reverted: false});
eq(f.planChange(none, 'inputAdded').action, 'install', 'first row on: install the guard');
eq(f.planChange(none, 'inputAdded').state, {input: true, powerOn: false, tries: 0, reverted: false}, 'first row on: marker holds the input');
eq(f.planChange(none, 'powerOnSet').state.powerOn, true, 'power-on app set: marker holds it');
eq(f.planChange(inOn, 'powerOnSet').action, 'marker', 'second row on: only the marker is written');
eq(f.planChange(bothOn, 'inputRemoved').action, 'marker', 'one row off, the other still on: marker only');
eq(f.planChange(inOn, 'inputRemoved').action, 'remove', 'last row off: the guard is removed');
eq(f.planChange(none, 'inputRemoved').action, 'remove', 'a row off with no marker: remove (idempotent)');
eq(f.planChange(c.serializeGuard({input: true, powerOn: false, tries: 2, reverted: false}), 'powerOnSet').state.tries, 0, 'a new change restarts the count');
eq(f.planChange(c.serializeGuard({input: false, powerOn: false, tries: 0, reverted: true}), 'inputAdded').state.reverted, false, 'a new change clears the reverted note');
eq(f.planStart(none).action, 'none', 'start: no marker, nothing to do');
eq(f.planStart(inOn).action, 'none', 'start: guard on, count 0, nothing to do');
eq(f.planStart(c.serializeGuard({input: true, powerOn: false, tries: 1, reverted: false})).action, 'reached', 'start: a counted boot, tell the guard Hearth reached its screen');
eq(f.planStart(c.serializeGuard({input: false, powerOn: false, tries: 3, reverted: false})).action, 'none', 'start: guard off, a stale count is ignored');
const rv = f.planStart(c.serializeGuard({input: false, powerOn: false, tries: 0, reverted: true}));
eq([rv.action, rv.clear, rv.state.reverted], ['reverted', 'remove', false], 'start: reverted and nothing left: say so once, remove the marker');
const rv2 = f.planStart(c.serializeGuard({input: true, powerOn: false, tries: 0, reverted: true}));
eq([rv2.action, rv2.clear, rv2.state.input, rv2.state.reverted], ['reverted', 'marker', true, false], 'start: reverted but the input is still listed: marker kept without the note');
eq(f.traceLines('a\n\nb\r\nc\n'), ['a', 'b', 'c'], 'trace: blank lines dropped, line ends cleaned');
eq(f.traceLines(Array.from({length: 250}, (_, i) => 'l' + i).join('\n')).length, 200, 'trace: only the last 200 lines');
eq(f.traceLines(Array.from({length: 250}, (_, i) => 'l' + i).join('\n'))[199], 'l249', 'trace: newest line last');
eq(f.traceLines('x'.repeat(300))[0].length, 200, 'trace: a line is cut to 200 characters');
eq(f.traceLines(''), [], 'trace: empty output gives no lines');
process.exit(fail ? 1 : 0);
