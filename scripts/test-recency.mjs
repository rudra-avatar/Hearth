// Tests for src/lib/recency.ts (Most used, 2.1.6 p5).   Run: npm test
import {build} from 'esbuild';
const out = new URL('../node_modules/.cache-recency-test.mjs', import.meta.url).pathname;
await build({entryPoints: [new URL('../src/lib/recency.ts', import.meta.url).pathname], bundle: true, format: 'esm', outfile: out, platform: 'node', logLevel: 'error'});
const o = await import(out);
let fail = 0;
const eq = (a, b, m) => { const ok = JSON.stringify(a) === JSON.stringify(b); if (!ok) { fail++; console.log('FAIL', m, JSON.stringify(a), '!=', JSON.stringify(b)); } else console.log('ok  ', m); };
const k = (x) => x;
const store = {};
globalThis.localStorage = {getItem: (n) => (n in store ? store[n] : null), setItem: (n, v) => { store[n] = String(v); }};
eq(o.noteRecent(['a', 'b'], 'c'), ['c', 'a', 'b'], 'a new tile goes to the front');
eq(o.noteRecent(['a', 'b', 'c'], 'c'), ['c', 'a', 'b'], 'an opened tile moves to the front once');
eq(o.noteRecent(Array.from({length: 80}, (_, i) => 'k' + i), 'n').length, 80, 'the list is capped');
eq(o.orderByUsage(['a', 'b', 'c', 'd'], k, {c: 5, a: 2}, [], []), ['c', 'a', 'b', 'd'], 'most opened first, never opened keep their order');
eq(o.orderByUsage(['a', 'b', 'c'], k, {}, [], []), ['a', 'b', 'c'], 'nothing opened yet: the manual order');
eq(o.orderByUsage(['a', 'b', 'c', 'd'], k, {d: 3, gone: 9, b: 1}, [], []), ['d', 'b', 'a', 'c'], 'a key no longer on the row is ignored');
eq(o.orderByUsage(['a', 'b', 'c', 'd'], k, {d: 3, c: 2, b: 1}, [], ['b']), ['d', 'b', 'c', 'a'], 'a favourite keeps its place (b stays second)');
eq(o.orderByUsage(['a', 'b', 'c'], k, {c: 3, b: 2, a: 1}, [], ['a', 'b', 'c']), ['a', 'b', 'c'], 'all favourites: unchanged');
eq(o.orderByUsage(['a', 'b', 'c'], k, {a: 2, b: 2, c: 2}, ['c', 'b'], []), ['c', 'b', 'a'], 'equal counts: the one opened last first, then the manual order');
eq(o.orderByUsage(['a', 'b', 'c'], k, {a: 1, b: 1, c: 1}, ['b', 'a', 'c'], []), ['b', 'a', 'c'], 'seeded from the old list: the old order stays');
eq(o.noteUsage({a: 1}, 'a'), {a: 2}, 'a count goes up');
eq(o.noteUsage({a: 1}, 'b'), {a: 1, b: 1}, 'a new tile starts at 1');
eq(o.noteUsage({a: 999, b: 10, c: 1}, 'a'), {a: 500, b: 5}, 'at 1000 every count is halved, zeros drop');
const big = {}; for (let i = 0; i < 200; i++) big['k' + i] = i + 1;
const grown = o.noteUsage(big, 'new');
eq(Object.keys(grown).length, 200, 'the table stays at 200 entries');
eq(grown.new, 1, 'the new tile is kept');
eq('k0' in grown, false, 'the lowest count is dropped');
eq(o.readUsage(), {}, 'no old list, nothing saved: empty counts');
store['customlauncher-recent-order'] = JSON.stringify(['x', 'y']);
eq(o.readUsage(), {x: 1, y: 1}, 'counts not saved yet: seeded from the old last-opened list');
eq('customlauncher-usage-counts' in store, false, 'reading the seed writes nothing');
o.writeUsage({x: 4});
eq(o.readUsage(), {x: 4}, 'saved counts are read back (no seed once saved)');
store['customlauncher-usage-counts'] = '{"x":"bad","y":-1,"z":2.7}';
eq(o.readUsage(), {z: 2}, 'bad values are ignored');
store['customlauncher-usage-counts'] = 'not json';
eq(o.readUsage(), {}, 'broken data: empty counts');
process.exit(fail ? 1 : 0);
